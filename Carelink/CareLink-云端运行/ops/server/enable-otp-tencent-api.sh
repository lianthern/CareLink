#!/usr/bin/env bash
# Enable the Tencent Cloud SES HTTP API OTP delivery adapter (tencent_ses_api) on a running server.
#
# Reads exactly two lines from stdin — SecretId, then SecretKey — and writes them, together with the
# non-secret parameters below, into a root-only (0600) systemd EnvironmentFile plus a small drop-in that
# points the unit at it. Never pass credentials as command-line arguments or environment variables to this
# script: they end up in `ps`, shell history and process-environment dumps. Everything else (region, from
# address, from name, template id, timeout) is read from THIS SCRIPT's own environment, which is safe
# because none of it is a secret.
#
# Usage (as root, on the server):
#   UNSEEN_TENCENT_SES_TEMPLATE_ID=100001 \
#     ./enable-otp-tencent-api.sh <<'EOF'
#   <SecretId>
#   <SecretKey>
#   EOF
#
# Optional overrides (all non-secret):
#   UNSEEN_TENCENT_SES_REGION       default: ap-guangzhou
#   UNSEEN_TENCENT_SES_FROM         default: no-reply@mail.maxxam.xyz
#   UNSEEN_TENCENT_SES_FROM_NAME    default: unset (adapter falls back to the bare address)
#   UNSEEN_TENCENT_SES_TEMPLATE_VARIABLE  default: code
#   UNSEEN_TENCENT_SES_TIMEOUT_MS   default: unset (adapter default applies)
#   UNSEEN_OPERABLE_SERVICE_NAME    default: unseen-operable
#   UNSEEN_OTP_ENV_FILE             default: /etc/unseen/otp-tencent-api.env
#   UNSEEN_OTP_DROPIN_DIR           default: /etc/systemd/system/${UNSEEN_OPERABLE_SERVICE_NAME}.service.d
#
# Idempotent: re-running with the same inputs reproduces the same env file and drop-in, then restarts the
# service. It never echoes the SecretId/SecretKey values (not to stdout, not to logs, not via `set -x`).
set -euo pipefail

if [[ "$(id -u)" -ne 0 ]]; then
  echo "enable-otp-tencent-api: must run as root" >&2
  exit 1
fi

service_name="${UNSEEN_OPERABLE_SERVICE_NAME:-unseen-operable}"
env_file="${UNSEEN_OTP_ENV_FILE:-/etc/unseen/otp-tencent-api.env}"
dropin_dir="${UNSEEN_OTP_DROPIN_DIR:-/etc/systemd/system/${service_name}.service.d}"
dropin_file="${dropin_dir}/50-otp-tencent-api.conf"

region="${UNSEEN_TENCENT_SES_REGION:-ap-guangzhou}"
from_address="${UNSEEN_TENCENT_SES_FROM:-no-reply@mail.maxxam.xyz}"
from_name="${UNSEEN_TENCENT_SES_FROM_NAME:-}"
template_id="${UNSEEN_TENCENT_SES_TEMPLATE_ID:-}"
template_variable="${UNSEEN_TENCENT_SES_TEMPLATE_VARIABLE:-code}"
timeout_ms="${UNSEEN_TENCENT_SES_TIMEOUT_MS:-}"

if [[ -z "${template_id}" ]]; then
  echo "enable-otp-tencent-api: UNSEEN_TENCENT_SES_TEMPLATE_ID is required (approved SES template id)" >&2
  exit 1
fi
if ! [[ "${template_id}" =~ ^[0-9]+$ ]]; then
  echo "enable-otp-tencent-api: UNSEEN_TENCENT_SES_TEMPLATE_ID must be a positive integer" >&2
  exit 1
fi

single_line() {
  # Rejects empty values and anything carrying a newline, so a fat-fingered multi-line paste fails closed
  # instead of silently truncating or corrupting the env file. (A literal NUL can't survive in a bash string
  # in the first place, so there is nothing to check for there.)
  local value="$1" label="$2"
  if [[ -z "${value}" ]]; then
    echo "enable-otp-tencent-api: ${label} must not be empty" >&2
    exit 1
  fi
  if [[ "${value}" == *$'\n'* ]]; then
    echo "enable-otp-tencent-api: ${label} must be a single line" >&2
    exit 1
  fi
}

IFS= read -r secret_id
IFS= read -r secret_key
single_line "${secret_id}" "SecretId"
single_line "${secret_key}" "SecretKey"
single_line "${region}" "UNSEEN_TENCENT_SES_REGION"
single_line "${from_address}" "UNSEEN_TENCENT_SES_FROM"
single_line "${template_variable}" "UNSEEN_TENCENT_SES_TEMPLATE_VARIABLE"
if [[ -n "${from_name}" ]]; then single_line "${from_name}" "UNSEEN_TENCENT_SES_FROM_NAME"; fi
if [[ -n "${timeout_ms}" ]]; then single_line "${timeout_ms}" "UNSEEN_TENCENT_SES_TIMEOUT_MS"; fi

install -d -m 0700 -o root -g root "$(dirname "${env_file}")"
install -d -m 0755 -o root -g root "${dropin_dir}"

tmp_env_file="$(mktemp "${env_file}.XXXXXX")"
trap 'rm -f "${tmp_env_file}"' EXIT
{
  echo "UNSEEN_OTP_DELIVERY_PROVIDER=tencent_ses_api"
  echo "UNSEEN_TENCENT_SES_SECRET_ID=${secret_id}"
  echo "UNSEEN_TENCENT_SES_SECRET_KEY=${secret_key}"
  echo "UNSEEN_TENCENT_SES_REGION=${region}"
  echo "UNSEEN_TENCENT_SES_FROM=${from_address}"
  if [[ -n "${from_name}" ]]; then echo "UNSEEN_TENCENT_SES_FROM_NAME=${from_name}"; fi
  echo "UNSEEN_TENCENT_SES_TEMPLATE_ID=${template_id}"
  echo "UNSEEN_TENCENT_SES_TEMPLATE_VARIABLE=${template_variable}"
  if [[ -n "${timeout_ms}" ]]; then echo "UNSEEN_TENCENT_SES_TIMEOUT_MS=${timeout_ms}"; fi
} > "${tmp_env_file}"
chown root:root "${tmp_env_file}"
chmod 0600 "${tmp_env_file}"
mv -f "${tmp_env_file}" "${env_file}"
trap - EXIT

tmp_dropin_file="$(mktemp "${dropin_file}.XXXXXX")"
trap 'rm -f "${tmp_dropin_file}"' EXIT
{
  echo "# Generated by ops/server/enable-otp-tencent-api.sh — do not edit by hand."
  echo "[Service]"
  echo "EnvironmentFile=${env_file}"
} > "${tmp_dropin_file}"
chown root:root "${tmp_dropin_file}"
chmod 0644 "${tmp_dropin_file}"
mv -f "${tmp_dropin_file}" "${dropin_file}"
trap - EXIT

unset secret_id secret_key

systemctl daemon-reload
systemctl restart "${service_name}"

echo "enable-otp-tencent-api: ${service_name} restarted with UNSEEN_OTP_DELIVERY_PROVIDER=tencent_ses_api" \
  "(env file: ${env_file}, drop-in: ${dropin_file})"
